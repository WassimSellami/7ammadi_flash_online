/**
 * Generates `dist/sw.js` after `vite build`.
 *
 * A plain precache of every emitted file (Vite already hashes bundles) plus a
 * navigation fallback. No plugin dependency, and the cache name changes with
 * the asset list so a redeploy invalidates cleanly.
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dist = join(root, "dist");

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

const all = walk(dist)
  .map((file) => `/${relative(dist, file).split(sep).join("/")}`)
  .filter((path) => path !== "/sw.js");

const hash = createHash("sha256")
  .update(
    all
      .slice()
      .sort()
      .map((path) => {
        const file = join(dist, path);
        const stat = statSync(file);
        return `${path}:${stat.size}:${Math.trunc(stat.mtimeMs)}`;
      })
      .join("|"),
  )
  .digest("hex")
  .slice(0, 12);

const precache = all.map((path) => path);
const version = `flash-${hash}`;

const source = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const RUNTIME = VERSION + "-runtime";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(VERSION).then(async (cache) => {
      await Promise.allSettled(PRECACHE.map((url) => cache.add(url)));
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then(async (keys) => {
      await Promise.all(keys.filter((key) => key !== VERSION && key !== RUNTIME).map((key) => caches.delete(key)));
    }).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/ws") || url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match("/index.html", { ignoreVary: true, ignoreSearch: true })
          .then((hit) => hit || caches.match("/", { ignoreVary: true, ignoreSearch: true }))
      )
    );
    return;
  }

  event.respondWith(
    caches.match(request, { ignoreVary: true, ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(request).then((response) => {
        if (!response || response.status !== 200 || response.type !== "basic") return response;
        const copy = response.clone();
        caches.open(RUNTIME).then((cache) => cache.put(request, copy)).catch(() => undefined);
        return response;
      });
    })
  );
});
`;

writeFileSync(join(dist, "sw.js"), source, "utf8");
console.log(`[sw] ${version}: ${precache.length} files precached`);
